import type { Level } from './sim';

/**
 * The 40 Pin Rescue levels (4 boxes of 10). Each map is 24 × 32 blocks (one block = 5 × 5 simulation cells):
 *   #  wall          x  wooden crate (lava burns it, bombs break it)
 *   ~  water         ^  lava         :  sand         $  gold         o  loose rock
 *   H  the jelly hero (3 × 3)        S  grumpy slime   B  bomb   G  gem
 *   1-9 pins (a run of the same digit); `dirs` gives the direction each pin slides out: l r u d.
 * `sol` is the designer's line: [seconds, pin index] (pin 1 = index 0). pin-rescue/test-niveles.mjs replays it and
 * checks it wins with 3 stars, that doing nothing never wins and that most wrong orders lose.
 * Boxes: 1 gold, lava and water (stone) · 2 slimes and sand · 3 crates, bombs and gems · 4 everything mixed.
 */

/** Bottom of most levels: a funnel down to the hero's slot (rows 20-31). */
const FUNNEL = [
  '##                    ##',
  '###                  ###',
  '####                ####',
  '#####              #####',
  '######            ######',
  '#######          #######',
  '########        ########',
  '########       #########',
  '########  HHH  #########',
  '########  HHH  #########',
  '########  HHH  #########',
  '########################',
];
/** Hero in the bottom-left corner: the floor slopes down to the left. */
const FUNNEL_L = [
  '#                 ######',
  '##               #######',
  '###             ########',
  '###            #########',
  '###           ##########',
  '###          ###########',
  '###         ############',
  '###        #############',
  '###HHH    ##############',
  '###HHH   ###############',
  '###HHH   ###############',
  '########################',
];
/** Hero in the bottom-right corner. */
const FUNNEL_R = FUNNEL_L.map((r) => [...r].reverse().join(''));
const OPEN = '#                      #';
const map = (top: string[], bottom = FUNNEL) => {
  const rows = [...top];
  while (rows.length < 32 - bottom.length) rows.push(OPEN);
  return [...rows, ...bottom];
};

/** A level seen in a mirror (pins slide the other way). */
const mirror = (L: Level): Level => ({
  ...L, map: L.map.map((r) => [...r].reverse().join('')),
  dirs: [...L.dirs].map((d) => (d === 'l' ? 'r' : d === 'r' ? 'l' : d)).join(''),
});
/** Swaps the standard bottom funnel (rows 20-31) of a level for another one. */
const rebottom = (L: Level, bottom: string[]): Level => ({ ...L, map: [...L.map.slice(0, 20), ...bottom] });

